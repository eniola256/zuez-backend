// Turns the 13 placeholder pieces into src/seed-demo.sql.
// Run:  node demo/make-demo-seed.js
import { writeFileSync } from "node:fs";
import { PRODUCTS, getVariants } from "./placeholder-products.js";

const NGN_PER_USD = 1500; // PLACEHOLDER rate, only used to invent demo naira prices
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
const asset = (p) => (p ? "/" + p.replace(/^\.\//, "") : "");

let sql = `-- DEMO DATA: the 13 placeholder pieces. Generated by demo/make-demo-seed.js.
-- Prices in naira are invented (USD x ${NGN_PER_USD}). Replace with your real clothes later.
-- WARNING: this wipes all products, stock and orders first.
TRUNCATE products, variants, stock, orders, order_items RESTART IDENTITY CASCADE;
`;

for (const p of PRODUCTS) {
  const slug = slugify(p.name);
  const cents = Math.round(p.price * 100);
  sql += `\nINSERT INTO products (slug, name, description, category, is_new, price_ngn, price_usd)
VALUES (${q(slug)}, ${q(p.name)}, ${q(p.description)}, ${q(p.cat)}, ${p.isNew ? "true" : "false"}, ${cents * NGN_PER_USD}, ${cents});\n`;

  getVariants(p).forEach((v, i) => {
    sql += `INSERT INTO variants (product_id, label, color, images, position)
VALUES ((SELECT id FROM products WHERE slug = ${q(slug)}), ${q(v.label)}, ${v.color ? q(v.color) : "NULL"}, ARRAY[${q(asset(v.img))}], ${i});\n`;

    const sizes = p.sizes?.length ? p.sizes : [""];
    for (const size of sizes) {
      const qty = (p.soldOut ?? []).includes(size) ? 0 : 10;
      sql += `INSERT INTO stock (variant_id, size, quantity)
VALUES ((SELECT v.id FROM variants v JOIN products p ON p.id = v.product_id WHERE p.slug = ${q(slug)} AND v.position = ${i}), ${q(size)}, ${qty});\n`;
    }
  });
}

writeFileSync(new URL("../src/seed-demo.sql", import.meta.url), sql);
console.log("wrote src/seed-demo.sql for", PRODUCTS.length, "products");
